-- Marks waiting alerts due when available stock (quantity - reserved) goes from 0 (or less) to
-- more than 0. A trigger, not service code, because many paths change stock (admin, cancel,
-- reservation release, refund) and any of them must fire the alert.
CREATE FUNCTION stock_alerts_mark_due() RETURNS trigger AS $$
BEGIN
  IF (OLD.quantity - OLD.reserved) <= 0 AND (NEW.quantity - NEW.reserved) > 0 THEN
    UPDATE stock_alerts SET due_at = now()
    WHERE variant_id = NEW.variant_id AND status = 'waiting' AND due_at IS NULL;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- HAND-WRITTEN (not generated by drizzle-kit): the back-in-stock trigger now only wakes the alerts of
-- the store whose shelf was refilled (an alert with no store, from before G4, wakes on any).
CREATE OR REPLACE FUNCTION stock_alerts_mark_due() RETURNS trigger AS $$
BEGIN
  IF (OLD.quantity - OLD.reserved) <= 0 AND (NEW.quantity - NEW.reserved) > 0 THEN
    UPDATE stock_alerts SET due_at = now()
    WHERE variant_id = NEW.variant_id AND status = 'waiting' AND due_at IS NULL
      AND (store_id IS NULL OR store_id = NEW.store_id);
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
